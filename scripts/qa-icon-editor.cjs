async page => {
  const checks = [], errors = [];
  page.setDefaultTimeout(15000);
  page.on('pageerror', error => errors.push(error.message));
  const assert = (condition, label) => { if (!condition) throw Error(label); checks.push(label); };
  const state = () => page.evaluate(async () => { const store = await import('./src/storage.js'); await store.flush(); return store.read('state'); });
  const editor = () => page.frameLocator('.icon-editor-frame');
  const open = async name => {
    await page.getByRole('button', {name, exact:true}).first().click({button:'right'});
    await page.getByRole('button', {name:'编辑图标', exact:true}).click();
    const frame = editor(); await frame.locator('html[data-ready="true"]').waitFor(); return frame;
  };
  const save = async frame => { await frame.getByRole('button', {name:'保 存', exact:true}).click(); await page.locator('#modal[open]').waitFor({state:'hidden'}); };
  try {
    await page.evaluate(async () => {
      const {createState}=await import('./src/model.js'); const {write}=await import('./src/storage.js');
      await write('state', createState(await (await fetch('./assets/seed.json')).json()));
    });
    await page.reload();
    await page.setViewportSize({width:1440,height:900});
    const before = await state();
    const original = before.groups[0].items.find(item => item.kind === 'site');
    let frame = await open(original.name);
    assert(await frame.locator('.el-dialog').evaluate(el => el.offsetWidth) === 740, '编辑窗口直接使用原版 740px 对话框');
    await frame.locator('.el-dialog').screenshot({path:'output/playwright/icon-editor.png',animations:'disabled'});
    await frame.locator('.icon-preview').filter({hasText:'文字图标'}).click();
    await frame.getByRole('textbox',{name:'图标文字',exact:true}).fill('文字图标测试');
    await frame.getByRole('textbox',{name:'名称',exact:true}).fill('图标编辑验收');
    await frame.locator('.colorTransparent').click();
    await save(frame);
    let item = (await state()).groups[0].items.find(item => item.id === original.id);
    assert(item.image === '' && item.iconText === '文字图标测试' && item.color === 'transparent', '图片切换文字并选择透明背景可保存');
    const tile = page.locator(`[data-item-id="${item.id}"] .site-face`);
    assert(await tile.evaluate(el => getComputedStyle(el).backgroundColor) === 'rgba(0, 0, 0, 0)', '主页透明背景没有白色底板');
    await page.reload();
    frame = await open('图标编辑验收');
    assert(await frame.getByRole('textbox',{name:'图标文字',exact:true}).inputValue() === '文字图标测试', '文字和背景刷新后保留');
    await frame.getByRole('textbox',{name:'名称',exact:true}).fill('取消后的名称');
    await frame.getByRole('button',{name:'Close this dialog'}).click();
    await page.locator('#modal[open]').waitFor({state:'hidden'});
    assert((await state()).groups[0].items.some(item => item.name === '图标编辑验收'), '关闭弹窗不保存草稿');
    frame = await open('图标编辑验收');
    await frame.locator('input[type="file"]').setInputFiles('assets/icon/icon_128.png');
    await frame.getByText('图标裁剪',{exact:true}).waitFor();
    await frame.locator('.vue-cropper img').first().waitFor();
    await frame.locator('.el-dialog').last().screenshot({path:'output/playwright/icon-cropper.png',animations:'disabled'});
    await frame.locator('.tabler-icon-refresh').click();
    await frame.locator('.tabler-icon-zoom-in').click();
    await frame.locator('.tabler-icon-zoom-out').click();
    await frame.getByRole('button',{name:'确 定',exact:true}).click();
    await frame.getByText('图标裁剪',{exact:true}).waitFor({state:'hidden'});
    await save(frame);
    item = (await state()).groups[0].items.find(item => item.id === original.id);
    assert(item.image.startsWith('data:image/png;base64,'), '上传、裁剪、旋转和缩放后图片保存为本地内容');
    await page.reload();
    const img = page.locator(`[data-item-id="${item.id}"] .site-face img`);
    assert(await img.evaluate(img => img.complete && img.naturalWidth > 0), '裁剪图标刷新后正常显示');
    frame = await open('图标编辑验收');
    await frame.locator('input[type="file"]').setInputFiles('assets/sites/cd550a920acff4.svg');
    await save(frame);
    item = (await state()).groups[0].items.find(item => item.id === original.id);
    assert(item.image.startsWith('data:image/svg+xml;base64,'), 'SVG 图标可以直接上传并保留矢量内容');
    const backupResult = await page.evaluate(async () => {
      const {read} = await import('./src/storage.js');
      const {makeBackup,parseBackup} = await import('./src/model.js');
      const original = await read('state'); return JSON.stringify(parseBackup(JSON.stringify(makeBackup(original))).groups) === JSON.stringify(original.groups);
    });
    assert(backupResult, '上传图标经过当前 JSON 备份往返保持完整');
    frame = await open('图标编辑验收');
    await frame.getByRole('button',{name:'获取图标',exact:true}).click();
    await frame.getByText('正在自动获取网站信息',{exact:false}).waitFor({state:'hidden',timeout:15000});
    const fetched = await frame.locator('.icon-preview').count();
    assert(fetched > 3, '真实网站信息接口获取候选图标');
    assert((await frame.locator('.icon-preview.active').innerText()).includes('官方图标'), '获取官方图标后按原版规则自动选择');
    await frame.getByRole('button',{name:'Close this dialog'}).click();
    await page.locator('#modal[open]').waitFor({state:'hidden'});
    await page.setViewportSize({width:390,height:844});
    frame = await open('图标编辑验收');
    assert(await frame.locator('body').evaluate(el => el.scrollWidth <= innerWidth), '390px 编辑器无横向溢出');
    await frame.locator('.icon-preview').filter({hasText:'文字图标'}).click();
    await frame.locator('.d-color-item').first().click();
    await page.screenshot({path:'output/playwright/icon-editor-mobile.png'});
    await frame.getByRole('button',{name:'Close this dialog'}).click();
    await page.locator('#modal[open]').waitFor({state:'hidden'});
    await page.setViewportSize({width:1440,height:900});
    await page.evaluate(async original => { const {write}=await import('./src/storage.js'); await write('state',original); }, before);
    await page.reload();
    await page.screenshot({path:'output/playwright/icon-home.png'});
    assert(errors.length === 0, '图标编辑工作流无未捕获 JavaScript 错误');
    return {checks,errors};
  } catch(error) { return {checks,errors,failure:error.message}; }
}
