async (page) => {
  page.setDefaultTimeout(10000);
  const checks=[];const assert=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.reload();
  await page.getByRole('button',{name:'主页设置',exact:true}).waitFor();
  await page.locator('#topbar').getByRole('button',{name:'添加组件',exact:true}).click();
  await page.locator('.widget-catalog').getByRole('button',{name:'待办事项',exact:false}).click();
  await page.getByRole('button',{name:'待办事项',exact:true}).click();
  await page.getByRole('textbox',{name:'新待办'}).fill('完成新标签页验收');
  await page.locator('#todo-form').getByRole('button',{name:'添加',exact:true}).click();
  await page.locator('.todo-list').getByText('完成新标签页验收').waitFor();
  assert(await page.locator('.todo-list').getByText('完成新标签页验收').count()===1,'待办可创建');
  await page.locator('.todo-list input[type=checkbox]').check();
  assert(await page.locator('.todo-list .done').count()===1,'待办可完成');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.locator('#topbar').getByRole('button',{name:'添加组件',exact:true}).click();
  await page.locator('.widget-catalog').getByRole('button',{name:'计算器',exact:false}).click();
  await page.getByRole('button',{name:'计算器',exact:true}).click();
  await page.getByRole('textbox',{name:'计算表达式'}).fill('(12+8)*5');
  await page.getByRole('button',{name:'=',exact:true}).click();
  assert(await page.locator('#calc-result').textContent()==='100','计算器真实运算');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'日历',exact:true}).click();
  const month=await page.locator('.month-nav h3').textContent();
  await page.getByRole('button',{name:'下一个月',exact:true}).click();
  assert((await page.locator('.month-nav h3').textContent())!==month,'日历支持翻月');
  await page.getByRole('button',{name:'回到今天',exact:true}).click();
  assert(await page.locator('.month-grid button.today').count()===1,'日历可回到今天');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'主页设置',exact:true}).click();
  await page.locator('[data-tab="wallpaper"]').click();
  await page.getByRole('switch',{name:'跟随系统主题',exact:true}).uncheck();
  await page.getByRole('combobox',{name:'主题模式',exact:true}).selectOption('dark');
  assert(await page.locator('html').getAttribute('data-theme')==='dark','深色主题即时生效');
  await page.locator('[data-wallpaper="forest"]').click();
  assert((await page.locator('#wallpaper').getAttribute('style')).includes('linear-gradient'),'渐变壁纸生效');
  await page.locator('#wallpaper-file').setInputFiles('assets/icon/icon_128.png');
  await page.getByText('当前：icon_128.png · 本地图片最多 8 MB',{exact:true}).waitFor();
  assert((await page.locator('#wallpaper').getAttribute('style')).includes('data:image/png'),'上传壁纸保存在本地数据中');
  await page.locator('[data-tab="backup"]').last().click();
  const backupDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出本地数据',exact:true}).click();
  await(await backupDownload).saveAs('output/playwright/backup-roundtrip.json');
  assert(true,'完整备份可导出');
  await page.getByRole('button',{name:'＋ 创建本机快照',exact:true}).click();
  await page.locator('.snapshot-row').filter({hasText:'手动备份'}).first().waitFor();
  assert(await page.locator('.snapshot-row').filter({hasText:'手动备份'}).count()>=1,'手动快照写入本机历史');
  await page.locator('[data-tab="wallpaper"]').click();
  await page.locator('[data-wallpaper="default"]').click();
  await page.getByRole('combobox',{name:'主题模式',exact:true}).selectOption('light');
  await page.locator('[data-tab="backup"]').last().click();
  await page.locator('#backup-file').setInputFiles('output/playwright/backup-roundtrip.json');
  await page.getByRole('button',{name:'确认',exact:true}).click();
  await page.getByText('备份恢复成功',{exact:true}).waitFor();
  assert(await page.locator('html').getAttribute('data-theme')==='dark'&&(await page.locator('#wallpaper').getAttribute('style')).includes('data:image/png'),'导入恢复主题和上传壁纸');
  assert(await page.locator('.snapshot-row').filter({hasText:'恢复前自动备份'}).count()>=1,'恢复前自动保留快照');
  await page.locator('#backup-file').setInputFiles('output/playwright/invalid.json');
  await page.getByText('这不是 iTab Local 备份文件',{exact:true}).waitFor();
  assert(await page.locator('html').getAttribute('data-theme')==='dark','非法备份被拒绝且不改变主页');
  await page.getByRole('button',{name:'关闭设置',exact:true}).click();
  await page.reload();
  await page.getByRole('button',{name:'待办事项',exact:true}).waitFor();
  assert(await page.locator('.widget-todo input[type=checkbox]').isChecked(),'待办完成状态随备份保留');
  assert((await page.locator('.notes-preview').textContent()).includes('自动保存测试'),'备忘录随备份保留');
  assert(errors.length===0,'组件和备份流程无未捕获错误');
  return {checks,errors};
}
